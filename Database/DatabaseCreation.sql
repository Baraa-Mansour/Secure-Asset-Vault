USE AssetVault

CREATE TABLE Users(
	Id INT PRIMARY KEY IDENTITY(1,1),
	Username NVARCHAR(100) UNIQUE NOT NULL,
	Email NVARCHAR(255) UNIQUE NOT NULL,
	PasswordHash VARBINARY(MAX) NOT NULL,
	-- password will be hashed
	PasswordSalt VARBINARY(MAX) NOT NULL,
	-- used for hashing 
	CreatedAt DATETIME2 NOT NULL DEFAULT(GETUTCDATE()),
	IsActive BIT NOT NULL DEFAULT(1),
	IsDeleted BIT NOT NULL DEFAULT(0)
);

CREATE TABLE Vaults(
	Id INT PRIMARY KEY IDENTITY(1,1),
	UserId INT FOREIGN KEY REFERENCES Users(Id) ON DELETE CASCADE NOT NULL,
	Name NVARCHAR(200) NOT NULL,
	Description NVARCHAR(1000),
	CreatedAt DATETIME2 NOT NULL DEFAULT(GETUTCDATE())
);

CREATE TABLE VaultItems(
	Id INT PRIMARY KEY IDENTITY(1,1),
	VaultId INT FOREIGN KEY REFERENCES Vaults(Id) ON DELETE CASCADE NOT NULL,
	Alias NVARCHAR(200) NOT NULL,
	-- user-friendly name for item
	EncryptedData VARBINARY(MAX) NOT NULL,
	EncryptedKey_ForUser VARBINARY(MAX) NOT NULL,
	-- use for decrypt (encrypted with user master key)
	IV VARBINARY(128) NOT NULL,
	CreatedAt DATETIME2 NOT NULL DEFAULT(GETUTCDATE()),
	UpdatedAt DATETIME2 NOT NULL DEFAULT(GETUTCDATE())
);

CREATE TABLE AuditLogs(
	Id BIGINT PRIMARY KEY IDENTITY(1,1),
	UserId INT FOREIGN KEY REFERENCES Users(Id),
	Action NVARCHAR(100) NOT NULL,
	ResourceId INT,
	Message NVARCHAR(MAX),
	IpAddress NVARCHAR(45),
	Timestamp DATETIME2 NOT NULL DEFAULT(GETUTCDATE()),
	Severity NVARCHAR(20) NOT NULL
	-- information / warning / error
);